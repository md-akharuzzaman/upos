#!/usr/bin/env bash
# 02 — GitHub setup: repository, team, CODEOWNERS, environments, QA sign-off,
#      variables, first push.
#
#   ./scripts/02-setup-github.sh                 create/configure repo and push this kit
#   ./scripts/02-setup-github.sh --protect-main  (later) require PR + review + green CI on main
#
# Team model (config/eurc.env): GITHUB_OWNER = team lead, DEV1 + DEV2 = developers,
# TESTER = QA engineer.
#   * every pull request needs 1 approving review that is not the author's
#   * code owners must approve their area: developers app/ web/ infra/,
#     tester tests/, lead + tester the pipeline (.github/)
#   * production deployments need approval from the tester (QA sign-off) or the
#     lead, and never from the person who triggered the run
#
# Order matters: environments and variables are created BEFORE the first push,
# because the push to main immediately starts the CD pipeline.
# shellcheck source=lib.sh
source "$(dirname "$0")/lib.sh"
require gh git jq
check_config

REPO="${GITHUB_OWNER}/${GITHUB_REPO}"
VALUES="${ROOT_DIR}/.github-values.env"

protect_main() {
  step "Ruleset: protect main"
  local body
  body=$(jq -n '{
    name: "protect-main", target: "branch", enforcement: "active",
    conditions: { ref_name: { include: ["~DEFAULT_BRANCH"], exclude: [] } },
    rules: [
      { type: "deletion" }, { type: "non_fast_forward" },
      { type: "pull_request", parameters: {
          required_approving_review_count: 1, dismiss_stale_reviews_on_push: true,
          require_code_owner_review: true, require_last_push_approval: true,
          required_review_thread_resolution: true } },
      { type: "required_status_checks", parameters: {
          strict_required_status_checks_policy: true,
          required_status_checks: [ {context: "app"}, {context: "web"}, {context: "infra"}, {context: "scripts"} ] } }
    ] }')
  existing=$(gh api "repos/${REPO}/rulesets" --jq '.[] | select(.name=="protect-main") | .id' || true)
  if [[ -n "$existing" ]]; then
    gh api -X PUT "repos/${REPO}/rulesets/${existing}" --input - <<<"$body" >/dev/null
  else
    gh api -X POST "repos/${REPO}/rulesets" --input - <<<"$body" >/dev/null
  fi
  ok "main now requires a pull request, 1 approval (code owners for their area), resolved threads and green app / web / infra / scripts"
}

if [[ "${1:-}" == "--protect-main" ]]; then protect_main; exit 0; fi

[[ -f "$VALUES" ]] || die "Run ./scripts/01-bootstrap-azure.sh first (missing .github-values.env)"
# shellcheck source=/dev/null
source "$VALUES"
gh auth status >/dev/null 2>&1 || die "Run: gh auth login"
GH_USER=$(gh api user --jq .login)
GH_USER_ID=$(gh api user --jq .id)

step "Repository ${REPO}"
if gh repo view "$REPO" >/dev/null 2>&1; then
  ok "exists"
else
  gh repo create "$REPO" "--${GITHUB_VISIBILITY}" \
    --description "eURC SaaS on Azure - Hands-on Project 02: Dev/Test/Prod with GitHub Actions CI/CD" >/dev/null
  ok "created (${GITHUB_VISIBILITY})"
fi

step "Team: collaborators"
for login in $(team_members); do
  if [[ "${login,,}" == "${GH_USER,,}" ]]; then ok "${login} (owner / lead)"; continue; fi
  if gh api "users/${login}" >/dev/null 2>&1; then
    # push = can create branches and pull requests; main itself is protected by the ruleset
    gh api -X PUT "repos/${REPO}/collaborators/${login}" -f permission=push >/dev/null
    ok "${login}: invited with write access (they must accept the e-mail invitation)"
  else
    warn "${login}: GitHub user not found - check config/eurc.env"
  fi
done

step "CODEOWNERS"
owners() { local o="" l; for l in "$@"; do [[ -n "$l" ]] && o+=" @${l}"; done; echo "${o# }"; }
mapfile -t dev_list < <(developers)
devs=$(owners "${dev_list[@]}")
[[ -n "$devs" ]] || devs="@${GITHUB_OWNER}"
qa=$(owners "${TESTER:-}")
[[ -n "$qa" ]] || qa="@${GITHUB_OWNER}"
cat > "${ROOT_DIR}/.github/CODEOWNERS" <<CODEOWNERS
# Generated by scripts/02-setup-github.sh from config/eurc.env.
# A pull request touching an area needs approval from one of its owners
# (never the author). Later lines win.
*                        ${devs}
/app/                    ${devs}
/web/                    ${devs}
/infra/                  ${devs}
/scripts/                ${devs}
/tests/                  ${qa}
/.github/                @${GITHUB_OWNER} ${qa}
/.github/CODEOWNERS      @${GITHUB_OWNER}
/docs/                   ${devs} ${qa}
CODEOWNERS
ok "developers ${devs} · tester ${qa} · pipeline @${GITHUB_OWNER} ${qa}"

step "Environments"
put_env() { # <name> <json>
  gh api -X PUT "repos/${REPO}/environments/$1" --input - <<<"$2" >/dev/null
}
branch_only_main() {
  local ids
  ids=$(gh api "repos/${REPO}/environments/$1/deployment-branch-policies" --jq '.branch_policies[].name' 2>/dev/null || true)
  [[ "$ids" == *main* ]] || gh api -X POST "repos/${REPO}/environments/$1/deployment-branch-policies" \
                                 -f name=main -f type=branch >/dev/null
}
for e in dev test; do
  put_env "$e" '{"deployment_branch_policy":{"protected_branches":false,"custom_branch_policies":true}}'
  branch_only_main "$e"
  ok "${e}: deploys from main only, no approval"
done
# QA sign-off: the tester approves production releases; the lead is the backup
# approver. prevent_self_review stops whoever triggered the run approving it.
reviewer_ids=()
for login in "${TESTER:-}" "$GITHUB_OWNER"; do
  [[ -n "$login" ]] || continue
  id=$(gh api "users/${login}" --jq .id 2>/dev/null || true)
  [[ -n "$id" ]] && reviewer_ids+=("$id")
done
prod_json() {
  printf '%s\n' "$@" | jq -R 'select(length > 0) | tonumber' | jq -s '{
    wait_timer: 0,
    prevent_self_review: (length > 1),
    reviewers: map({ type: "User", id: . }),
    deployment_branch_policy: { protected_branches: false, custom_branch_policies: true } }'
}
if put_env prod "$(prod_json "${reviewer_ids[@]}")"; then
  branch_only_main prod
  ok "prod: main only; QA sign-off by ${TESTER:-<no tester>} or lead ${GITHUB_OWNER}; self-approval blocked"
elif put_env prod "$(prod_json "$GH_USER_ID")"; then
  branch_only_main prod
  warn "prod: tester could not be added as reviewer yet (invitation not accepted?). Using ${GH_USER} only."
  warn "      Re-run ./scripts/02-setup-github.sh after ${TESTER} accepts the invitation."
else
  die "Could not set the prod approval rule. On a private repo this needs GitHub Pro / Team (Student Pack); or set GITHUB_VISIBILITY=public."
fi

step "Variables (no secrets: OIDC needs only IDs)"
gh variable set AZURE_TENANT_ID       -R "$REPO" --body "$AZURE_TENANT_ID"
gh variable set AZURE_SUBSCRIPTION_ID -R "$REPO" --body "$AZURE_SUBSCRIPTION_ID"
for e in $ENVIRONMENTS; do
  cid_var="AZURE_CLIENT_ID_${e^^}"; rg_var="AZURE_RESOURCE_GROUP_${e^^}"
  gh variable set AZURE_CLIENT_ID      -R "$REPO" --env "$e" --body "${!cid_var}"
  gh variable set AZURE_RESOURCE_GROUP -R "$REPO" --env "$e" --body "${!rg_var}"
  ok "${e}: AZURE_CLIENT_ID, AZURE_RESOURCE_GROUP"
done
gh variable set ALERT_EMAIL -R "$REPO" --env prod --body "$ALERT_EMAIL"
ok "prod: ALERT_EMAIL"

step "Push the kit (this starts the first CD run)"
cd "$ROOT_DIR" || exit 1
if [[ ! -d .git ]]; then git init -q -b main; fi
git config user.name  >/dev/null || git config user.name "$GH_USER"
git config user.email >/dev/null || git config user.email "${GH_USER_ID}+${GH_USER}@users.noreply.github.com"
gh auth setup-git >/dev/null 2>&1 || true
git remote get-url origin >/dev/null 2>&1 || git remote add origin "https://github.com/${REPO}.git"
git add -A
git diff --cached --quiet || git commit -q -m "eURC Hands-on 02: app, Bicep, GitHub Actions CI/CD, scripts"
git push -u origin main
ok "Pushed. Watch it: https://github.com/${REPO}/actions"
echo
echo "  The prod job will wait for your approval:"
echo "  Actions > CD > the run > 'Review deployments' > tick prod > Approve and deploy"
echo
ok "After the first green run, protect main with: ./scripts/02-setup-github.sh --protect-main"
